"""The retrieval gold set.

Ground truth is **not** generated by a language model. A model asked to judge which
objects answer a question would be graded against its own opinion, which measures
agreement with itself rather than retrieval quality.

Entries therefore carry a review status, and the benchmark reports unreviewed entries
separately from reviewed ones. A `draft` entry is a candidate for a human to accept,
amend or reject — its numbers are indicative only and are labelled as such.

The file is versioned: changing the corpus or the judgements changes the version, so two
benchmark runs are only comparable when they cite the same gold version.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path

from pydantic import BaseModel, Field

from researchagent.core.exceptions import ConfigurationError
from researchagent.models.knowledge import KnowledgeKind


class ReviewStatus(StrEnum):
    """Whether a human has actually checked this judgement."""

    # Proposed mechanically from the corpus; not yet accepted by a person.
    DRAFT = "draft"
    # A person has read the objects and confirmed the judgements.
    REVIEWED = "reviewed"


class Relevance(StrEnum):
    """Graded relevance. nDCG uses the numeric gain."""

    HIGHLY_RELEVANT = "highly_relevant"
    RELEVANT = "relevant"
    MARGINAL = "marginal"

    @property
    def gain(self) -> float:
        return {"highly_relevant": 3.0, "relevant": 2.0, "marginal": 1.0}[self.value]


class GoldJudgement(BaseModel):
    """One object judged relevant to one query, with why."""

    model_config = {"frozen": True}

    knowledge_object_id: str = Field(min_length=1)
    relevance: Relevance = Relevance.RELEVANT
    # Recorded so a reviewer can check the judgement without re-deriving it.
    rationale: str = ""


class GoldQuery(BaseModel):
    """One benchmark query and its expected results."""

    model_config = {"frozen": True}

    id: str = Field(min_length=1)
    text: str = Field(min_length=1)
    kinds: tuple[KnowledgeKind, ...] = ()
    paper_ids: tuple[str, ...] = ()
    judgements: tuple[GoldJudgement, ...] = ()
    relevant_evidence_ids: tuple[str, ...] = ()
    status: ReviewStatus = ReviewStatus.DRAFT
    reviewed_by: str | None = None
    notes: str = ""

    @property
    def relevant_ids(self) -> set[str]:
        return {judgement.knowledge_object_id for judgement in self.judgements}

    @property
    def grades(self) -> dict[str, float]:
        return {
            judgement.knowledge_object_id: judgement.relevance.gain for judgement in self.judgements
        }


class GoldSet(BaseModel):
    """A versioned collection of benchmark queries."""

    model_config = {"frozen": True}

    version: str = Field(min_length=1)
    corpus_description: str = ""
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    queries: tuple[GoldQuery, ...] = ()

    @property
    def reviewed(self) -> tuple[GoldQuery, ...]:
        return tuple(q for q in self.queries if q.status is ReviewStatus.REVIEWED)

    @property
    def drafts(self) -> tuple[GoldQuery, ...]:
        return tuple(q for q in self.queries if q.status is ReviewStatus.DRAFT)

    @property
    def is_fully_reviewed(self) -> bool:
        return bool(self.queries) and not self.drafts

    @classmethod
    def load(cls, path: Path) -> GoldSet:
        if not path.is_file():
            raise ConfigurationError("Gold set not found", file=str(path))
        try:
            return cls.model_validate_json(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ConfigurationError(
                "Gold set could not be read", file=str(path), reason=str(exc)
            ) from exc

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.model_dump_json(indent=2), encoding="utf-8")
